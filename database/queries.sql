-- Query 18: Order Cancellation Rate
-- Business Question: What percentage of total generated invoices represent returns or cancellations?
-- Formula: (Cancelled Invoices / Total Invoices) * 100
-- Tables Used: fact_sales
SELECT 
    COUNT(DISTINCT invoice_no) AS total_invoices,
    COUNT(DISTINCT CASE WHEN is_cancellation = TRUE THEN invoice_no END) AS cancelled_invoices,
    ROUND(
        (COUNT(DISTINCT CASE WHEN is_cancellation = TRUE THEN invoice_no END)::NUMERIC / NULLIF(COUNT(DISTINCT invoice_no), 0)) * 100, 2
    ) AS cancellation_rate_pct
FROM fact_sales;


-- Query 19: Refund & Cancellation Monetary Loss
-- Business Question: How much total revenue was lost to cancellations and returns?
-- Tables Used: fact_sales
