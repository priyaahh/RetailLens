-- Query 21: Month-over-Month (MoM) Revenue Growth Rate (CTE + LAG Window Function)
-- Business Question: What is the monthly revenue percentage growth rate compared to the previous month?
WITH monthly_revenue AS (
    SELECT 
        invoice_year,
        invoice_month,
        SUM(total_amount) AS current_month_revenue
    FROM fact_sales
    WHERE is_cancellation = FALSE
    GROUP BY invoice_year, invoice_month
),
monthly_with_lag AS (
    SELECT 
        invoice_year,
        invoice_month,
        current_month_revenue,
        LAG(current_month_revenue, 1) OVER (ORDER BY invoice_year, invoice_month) AS previous_month_revenue
    FROM monthly_revenue
)
SELECT 
    invoice_year,
    invoice_month,
    current_month_revenue,
    COALESCE(previous_month_revenue, 0.00) AS previous_month_revenue,
    ROUND(
        ((current_month_revenue - previous_month_revenue) / NULLIF(previous_month_revenue, 0.00)) * 100, 2
    ) AS mom_growth_pct
FROM monthly_with_lag
ORDER BY invoice_year ASC, invoice_month ASC;


-- Query 22: Top 3 Products per Country (CTE + DENSE_RANK Window Function)
-- Business Question: Which top 3 revenue-generating products belong to each country market?
WITH country_product_revenue AS (
    SELECT 
        country,
        stock_code,
        description,
        SUM(total_amount) AS total_revenue,
        DENSE_RANK() OVER (PARTITION BY country ORDER BY SUM(total_amount) DESC) AS revenue_rank
    FROM fact_sales
    WHERE is_cancellation = FALSE
    GROUP BY country, stock_code, description
)
SELECT 
    country,
    revenue_rank,
    stock_code,
    description,
    total_revenue
FROM country_product_revenue
WHERE revenue_rank <= 3
ORDER BY country ASC, revenue_rank ASC;


-- Query 23: Customer Spending Leaderboard with Percent Contribution (Window Functions)
-- Business Question: Rank customers by revenue and calculate their percentage contribution to total sales.
WITH customer_totals AS (
    SELECT 
        customer_id,
        customer_type,
        COUNT(DISTINCT invoice_no) AS total_orders,
        SUM(total_amount) AS total_spent
    FROM fact_sales
    WHERE is_cancellation = FALSE AND customer_id != 'GUEST'
    GROUP BY customer_id, customer_type
)
SELECT 
    DENSE_RANK() OVER (ORDER BY total_spent DESC) AS customer_rank,
    customer_id,
    customer_type,
    total_orders,
    total_spent,
    ROUND(
        (total_spent / SUM(total_spent) OVER ()) * 100, 2
    ) AS pct_of_total_revenue
FROM customer_totals
ORDER BY customer_rank ASC
LIMIT 20;


-- Query 24: Cumulative Running Total Revenue (Window Function)
-- Business Question: What is the cumulative running total revenue trajectory over time?
WITH daily_revenue AS (
    SELECT 
        DATE_TRUNC('day', invoice_timestamp) AS sales_date,
        SUM(total_amount) AS daily_revenue
    FROM fact_sales
    WHERE is_cancellation = FALSE
    GROUP BY DATE_TRUNC('day', invoice_timestamp)
)
SELECT 
    sales_date,
    daily_revenue,
    SUM(daily_revenue) OVER (ORDER BY sales_date ASC) AS cumulative_running_revenue
FROM daily_revenue
ORDER BY sales_date ASC;


-- Query 25: Customer Recency & Purchase Frequency Analysis (Subquery + Date Functions)
-- Business Question: Find the first purchase date, last purchase date, and order count for registered accounts.
SELECT 
    customer_id,
    COUNT(DISTINCT invoice_no) AS total_orders,
    MIN(invoice_timestamp) AS first_purchase_date,
    MAX(invoice_timestamp) AS last_purchase_date,
    SUM(total_amount) AS lifetime_value
FROM fact_sales
WHERE is_cancellation = FALSE AND customer_id != 'GUEST'
GROUP BY customer_id
HAVING COUNT(DISTINCT invoice_no) > 1
ORDER BY lifetime_value DESC;
