-- Query 1: Total Net Revenue
-- Business Question: What is the total net monetary revenue generated across all completed sales?
-- Tables Used: fact_sales
-- Index Tip: idx_fact_sales_cancellation
SELECT 
    COALESCE(SUM(total_amount), 0.00) AS total_revenue
FROM fact_sales
WHERE is_cancellation = FALSE;


-- Query 2: Total Completed Orders
-- Business Question: How many distinct completed sales transactions occurred?
-- Tables Used: fact_sales
-- Index Tip: idx_fact_sales_invoice_no
SELECT 
    COUNT(DISTINCT invoice_no) AS total_orders
FROM fact_sales
WHERE is_cancellation = FALSE;


-- Query 3: Total Units Sold
-- Business Question: How many individual item units were sold across all orders?
-- Tables Used: fact_sales
SELECT 
    COALESCE(SUM(quantity), 0) AS total_units_sold
FROM fact_sales
WHERE is_cancellation = FALSE;


-- Query 4: Average Order Value (AOV)
-- Business Question: What is the average monetary value per completed order?
-- Formula: Total Net Revenue / Total Distinct Orders
-- Tables Used: fact_sales
SELECT 
    ROUND(
        COALESCE(SUM(total_amount), 0.00) / NULLIF(COUNT(DISTINCT invoice_no), 0), 2
    ) AS average_order_value
FROM fact_sales
WHERE is_cancellation = FALSE;


-- Query 5: Average Unit Price
-- Business Question: What is the average selling price per item?
-- Tables Used: fact_sales
SELECT 
    ROUND(AVG(unit_price), 2) AS average_unit_price
FROM fact_sales
WHERE is_cancellation = FALSE;


-- Query 6: Total Distinct Customers
-- Business Question: How many distinct buyers (including guest checkout marker) placed orders?
-- Tables Used: fact_sales
-- Index Tip: idx_fact_sales_customer_id
SELECT 
    COUNT(DISTINCT customer_id) AS total_customers
FROM fact_sales;


-- Query 7: Registered vs Guest Customer Count
-- Business Question: How many distinct registered customers vs guest checkouts exist?
-- Tables Used: fact_sales
SELECT 
    customer_type,
    COUNT(DISTINCT customer_id) AS customer_count
FROM fact_sales
GROUP BY customer_type;


-- Query 8: Revenue by Country
-- Business Question: How much revenue is generated by each geographic market?
-- Tables Used: fact_sales
-- Index Tip: idx_fact_sales_country
SELECT 
    country,
    COUNT(DISTINCT invoice_no) AS total_orders,
    SUM(total_amount) AS total_revenue
FROM fact_sales
WHERE is_cancellation = FALSE
GROUP BY country
ORDER BY total_revenue DESC;


